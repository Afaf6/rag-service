const mongoose = require('mongoose');

const chunkSchema = new mongoose.Schema(
  {
    // Identifies the patient who owns this chunk.
    // This is critical for patient data isolation.
    patientId: {
      type: String,
      required: true,
      index: true,
    },

    // Identifies the original document this chunk belongs to.
    documentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Document',
      required: true,
      index: true,
    },

    // The actual text stored in this chunk.
    text: {
      type: String,
      required: true,
    },

    // Position of this chunk inside the original document.
    chunkIndex: {
      type: Number,
      required: true,
    },

    // Embedding vector generated by the embedding model.
    embedding: {
      type: [Number],
      required: true,
    },

    // Additional information about the original document.
    metadata: {
      originalFilename: {
        type: String,
      },

      category: {
        type: String,
      },
    },
  },
  {
    timestamps: true,
  }
);

/**
 * Compound index used when retrieving
 * all chunks belonging to a specific patient document.
 */
chunkSchema.index({
  patientId: 1,
  documentId: 1,
});

/**
 * Prevent duplicate chunk indexes inside the same document.
 *
 * This means one document cannot contain:
 *
 * documentId = X, chunkIndex = 0
 * documentId = X, chunkIndex = 0
 *
 * But another document can still have chunkIndex = 0,
 * which is correct.
 */
chunkSchema.index(
  {
    documentId: 1,
    chunkIndex: 1,
  },
  {
    unique: true,
  }
);

module.exports = mongoose.model('Chunk', chunkSchema);